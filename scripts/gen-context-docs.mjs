#!/usr/bin/env node
// scripts/gen-context-docs.mjs
// Deterministic generator for:
//   .github/CLIENT_MODULE_REFERENCE.md     (full overwrite)
//   .github/copilot-instructions.md        (block replacement only — preserves all prose)
//
// Usage:
//   node ./scripts/gen-context-docs.mjs           write mode
//   node ./scripts/gen-context-docs.mjs --check   verify mode (exits non-zero if drift)
//
// Determinism guarantees:
//   - NO wall-clock timestamps in any output
//   - All scripts sorted alphabetically by key
//   - All type names sorted alphabetically within each file section
//   - Module paths sorted alphabetically
//   - LF (\n) line endings throughout
//   - Node.js built-ins only — no external dependencies

import fs from 'node:fs';
import path from 'node:path';

const scriptDir = new URL('.', import.meta.url).pathname.replace(/\/$/, '');
const root = path.resolve(scriptDir, '..');
const CHECK_MODE = process.argv.includes('--check');

const PROVENANCE =
  '<!-- Generated by scripts/gen-context-docs.mjs from source. DO NOT EDIT BY HAND. -->';

// ── Utilities ─────────────────────────────────────────────────────────────────

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

/**
 * Walk a directory recursively, collecting .ts/.tsx files.
 * Excludes: test/ and __tests__/ directories; *.test.ts(x) and *.spec.ts(x) files.
 * Entries at each level are sorted alphabetically by name for determinism.
 */
function walkTs(dir, results = []) {
  if (!fs.existsSync(dir)) return results;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'test' || entry.name === '__tests__') continue;
      walkTs(full, results);
    } else if (
      entry.isFile() &&
      /\.(ts|tsx)$/.test(entry.name) &&
      !/\.(test|spec)\.(ts|tsx)$/.test(entry.name)
    ) {
      results.push(full);
    }
  }
  return results;
}

/**
 * Extract named exports matching: export (type|interface|class|const|enum) Name
 * Groups by file (relative to srcDir), sorted by relative path.
 * Types within each file are sorted alphabetically by name.
 */
function extractExports(srcDir) {
  const files = walkTs(srcDir);
  const exportRe = /^export\s+(type|interface|class|const|enum)\s+(\w+)/;
  const byFile = [];

  for (const file of files) {
    const rel = path.relative(srcDir, file).replace(/\\/g, '/');
    const lines = fs.readFileSync(file, 'utf8').split('\n');
    const exports = [];
    for (const line of lines) {
      const m = exportRe.exec(line);
      if (m) {
        exports.push({ kind: m[1], name: m[2] });
      }
    }
    if (exports.length > 0) {
      exports.sort((a, b) => a.name.localeCompare(b.name));
      byFile.push({ file: rel, exports });
    }
  }

  // Sort by relative file path for deterministic output
  byFile.sort((a, b) => a.file.localeCompare(b.file));
  return byFile;
}

// ── Module map ────────────────────────────────────────────────────────────────

/**
 * Build the module map by inspecting packages/*.
 * TypeScript packages: have package.json.
 * Go modules: have go.mod.
 * Rust crates (Tauri): have src-tauri/Cargo.toml.
 * Results sorted by package directory name.
 */
function buildModuleMap() {
  const pkgsDir = path.join(root, 'packages');
  const pkgDirs = fs.readdirSync(pkgsDir).sort();
  const modules = [];

  for (const d of pkgDirs) {
    const pkgPath = path.join(pkgsDir, d);
    if (!fs.statSync(pkgPath).isDirectory()) continue;

    const pkgJsonPath = path.join(pkgPath, 'package.json');
    const goModPath = path.join(pkgPath, 'go.mod');
    const cargoPath = path.join(pkgPath, 'src-tauri', 'Cargo.toml');

    if (fs.existsSync(pkgJsonPath)) {
      const pkg = readJson(pkgJsonPath);
      modules.push({ name: pkg.name, location: `packages/${d}`, lang: 'TypeScript' });
    } else if (fs.existsSync(goModPath)) {
      const modContent = fs.readFileSync(goModPath, 'utf8');
      const m = /^module\s+(\S+)/m.exec(modContent);
      modules.push({ name: m ? m[1] : d, location: `packages/${d}`, lang: 'Go' });
    } else if (fs.existsSync(cargoPath)) {
      const cargoContent = fs.readFileSync(cargoPath, 'utf8');
      const m = /^name\s*=\s*"([^"]+)"/m.exec(cargoContent);
      modules.push({ name: m ? `${m[1]} (crate)` : d, location: `packages/${d}`, lang: 'Rust' });
    }
  }

  return modules;
}

// ── Content generators ────────────────────────────────────────────────────────

function generateModuleMapContent(modules) {
  const header = ['| Package | Location | Language |', '|---------|----------|----------|'];
  const rows = modules.map(
    (m) => `| \`${m.name}\` | \`${m.location}\` | ${m.lang} |`,
  );
  return [...header, ...rows].join('\n');
}

function generateCommandsContent(scripts) {
  const header = ['| Script | Command |', '|--------|---------|'];
  const rows = Object.entries(scripts)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `| \`${k}\` | \`${v.replace(/\|/g, '\\|')}\` |`);
  return [...header, ...rows].join('\n');
}

function generateClientModuleRef(clientExports, sharedExports) {
  const lines = [
    PROVENANCE,
    '',
    '# Client Module Type Reference',
    '',
    'Public types and constants exported from Engine client packages.',
    '',
    '## packages/client/src',
    '',
  ];

  for (const { file, exports } of clientExports) {
    lines.push(`### ${file}`, '');
    for (const e of exports) {
      lines.push(`- \`${e.name}\` (${e.kind})`);
    }
    lines.push('');
  }

  lines.push('## packages/shared/src', '');

  for (const { file, exports } of sharedExports) {
    lines.push(`### ${file}`, '');
    for (const e of exports) {
      lines.push(`- \`${e.name}\` (${e.kind})`);
    }
    lines.push('');
  }

  // Normalize to single trailing newline
  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  lines.push('');

  return lines.join('\n');
}

// ── Block replacement ─────────────────────────────────────────────────────────

/**
 * Replace or insert a generated block in content.
 * If markers exist, replaces the content between them.
 * If markers don't exist, appends the block at the end.
 */
function replaceBlock(content, blockName, innerContent) {
  const begin = `<!-- BEGIN GENERATED:${blockName} -->`;
  const end = `<!-- END GENERATED:${blockName} -->`;
  const beginIdx = content.indexOf(begin);
  const endIdx = content.indexOf(end);

  if (beginIdx === -1 || endIdx === -1) {
    // Markers absent — append at end (drift for check mode, fallback for write mode)
    const trimmed = content.trimEnd();
    return `${trimmed}\n\n${begin}\n${innerContent}\n${end}\n`;
  }

  const before = content.slice(0, beginIdx + begin.length);
  const after = content.slice(endIdx);
  return `${before}\n${innerContent}\n${after}`;
}

// ── Main ──────────────────────────────────────────────────────────────────────

const pkgScripts = readJson(path.join(root, 'package.json')).scripts || {};
const modules = buildModuleMap();
const clientExports = extractExports(path.join(root, 'packages', 'client', 'src'));
const sharedExports = extractExports(path.join(root, 'packages', 'shared', 'src'));

const moduleMapContent = generateModuleMapContent(modules);
const commandsContent = generateCommandsContent(pkgScripts);
const clientModuleRef = generateClientModuleRef(clientExports, sharedExports);

const instructionsPath = path.join(root, '.github', 'copilot-instructions.md');
const clientRefPath = path.join(root, '.github', 'CLIENT_MODULE_REFERENCE.md');

const currentInstructions = fs.readFileSync(instructionsPath, 'utf8');
const expectedInstructions = replaceBlock(
  replaceBlock(currentInstructions, 'MODULE_MAP', moduleMapContent),
  'COMMANDS',
  commandsContent,
);

if (CHECK_MODE) {
  const drifted = [];

  const currentRef = fs.existsSync(clientRefPath)
    ? fs.readFileSync(clientRefPath, 'utf8')
    : '';
  if (currentRef !== clientModuleRef) {
    drifted.push('.github/CLIENT_MODULE_REFERENCE.md');
  }

  if (currentInstructions !== expectedInstructions) {
    drifted.push('.github/copilot-instructions.md');
  }

  if (drifted.length > 0) {
    process.stderr.write('context-docs drift detected in:\n');
    for (const f of drifted) process.stderr.write(`  ${f}\n`);
    process.stderr.write('Run: node ./scripts/gen-context-docs.mjs\n');
    process.exit(1);
  }

  process.stdout.write('context-docs: up to date\n');
  process.exit(0);
} else {
  fs.writeFileSync(clientRefPath, clientModuleRef, { encoding: 'utf8' });
  fs.writeFileSync(instructionsPath, expectedInstructions, { encoding: 'utf8' });
  process.stdout.write('Generated .github/CLIENT_MODULE_REFERENCE.md\n');
  process.stdout.write('Updated .github/copilot-instructions.md (generated blocks)\n');
}
